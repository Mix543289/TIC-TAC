#include "../libft.h"

char	*ft_strdup(const char *s)
{
	size_t			i;
	char			*result;

	i = 0;
	while (s[i])
		i++;
	result = (char *)malloc(i + 1);
	if (result == NULL)
		return (NULL);
	i = 0;
	while (s[i])
	{
		result[i] = s[i];
		i++;
	}
	result[i] = '\0';
	return (result);
}
