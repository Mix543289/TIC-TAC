#include "../libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	size_t			i;
	unsigned char	*j;

	i = 0;
	j = (unsigned char *)s;
	while (i < n)
	{
		if (j[i] == (unsigned char)c)
			return ((char *)&j[i]);
		i++;
	}
	return (0);
}
